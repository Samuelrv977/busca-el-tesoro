-- Esquema de la base de datos H2 en memoria para Búsqueda del Tesoro

CREATE TABLE IF NOT EXISTS jugadores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    nivel INT NOT NULL DEFAULT 1,
    puntos INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS partidas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jugador_id BIGINT NOT NULL,
    estado VARCHAR(30) NOT NULL,
    fecha_inicio TIMESTAMP NOT NULL,
    tesoro_encontrado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_partidas_jugador FOREIGN KEY (jugador_id) REFERENCES jugadores(id)
);

CREATE TABLE IF NOT EXISTS estadisticas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jugador_id BIGINT NOT NULL UNIQUE,
    partidas_jugadas INT NOT NULL DEFAULT 0,
    tesoros_encontrados INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_estadisticas_jugador FOREIGN KEY (jugador_id) REFERENCES jugadores(id)
);

CREATE TABLE IF NOT EXISTS islas_catalogo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(300) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    rel_x DOUBLE PRECISION NOT NULL,
    rel_y DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS pistas_catalogo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(400) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    categoria VARCHAR(40) NOT NULL,
    respuesta_correcta VARCHAR(100) NOT NULL,
    puntos_recompensa INT NOT NULL DEFAULT 40
);

CREATE TABLE IF NOT EXISTS respuestas_catalogo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR(100) NOT NULL,
    categoria VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS tesoros_catalogo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    descripcion VARCHAR(300) NOT NULL,
    puntos_base INT NOT NULL DEFAULT 150
);
